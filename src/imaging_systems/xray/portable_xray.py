    def acquire(
        self,
        exposure_params: Optional[ExposureParameters] = None,
        anatomical_region: str = "chest",
        **params,
    ) -> ImageData:
        """Acquire X-ray image."""
        if not self.is_ready:
            raise RuntimeError(f"Device not ready. Current status: {self._status}")

        if exposure_params is None:
            exposure_params = self._get_default_exposure(anatomical_region)

        if not exposure_params.validate():
            raise ValueError("Invalid exposure parameters")

        if not self._tube.can_expose(
            exposure_params.kvp,
            exposure_params.ma,
            exposure_params.exposure_time,
        ):
            raise RuntimeError("Tube heat capacity exceeded. Allow cooling.")

        self._status = DeviceStatus.ACQUIRING

        try:
            # Simulate X-ray exposure
            image_data = self._perform_exposure(exposure_params)

            # Update tube heat
            self._tube.add_heat(
                exposure_params.kvp,
                exposure_params.ma,
                exposure_params.exposure_time,
            )

            # Update battery
            self._battery_level -= 0.5

            self._exposure_count += 1
            self._last_acquisition = datetime.now()
            self._status = DeviceStatus.READY

            return ImageData(
                data=image_data,
                timestamp=self._last_acquisition,
                metadata={
                    "modality": "xray",
                    "kvp": exposure_params.kvp,
                    "ma": exposure_params.ma,
                    "exposure_time": exposure_params.exposure_time,
                    "mas": exposure_params.mas,
                    "sfd_cm": exposure_params.sfd,
                    "focal_spot": exposure_params.focal_spot,
                    "anatomical_region": anatomical_region,
                    "exposure_number": self._exposure_count,
                },
                device_id=self.device_id,
                modality="xray",
            )
        except Exception as e:
            self.log_error(f"Acquisition failed: {str(e)}")
            raise

    def _get_default_exposure(self, anatomical_region: str) -> ExposureParameters:
        """Get default exposure parameters for anatomical region."""
        presets = {
            "chest": ExposureParameters(110, 200, 0.02, "large", 180),
            "hand": ExposureParameters(50, 100, 0.01, "small", 100),
            "pelvis": ExposureParameters(80, 320, 0.05, "large", 100),
            "spine": ExposureParameters(85, 250, 0.04, "large", 100),
            "skull": ExposureParameters(75, 200, 0.03, "large", 100),
            "abdomen": ExposureParameters(80, 250, 0.05, "large", 100),
        }
        return presets.get(anatomical_region, self._default_exposure)

    def _perform_exposure(self, params: ExposureParameters) -> np.ndarray:
        """Perform X-ray exposure and generate image."""
        # Simulate detector response
        detector_size = (2048, 2048)

        # Generate base image with quantum noise
        exposure_level = params.kvp * params.mas / 1000
        base_intensity = exposure_level * 1000

        # Poisson noise (quantum mottle)
        image = np.random.poisson(base_intensity, detector_size).astype(np.float64)

        # Add some anatomical structure simulation
        image = self._add_simulated_anatomy(image, params)

        # Apply logarithmic transformation
        image = np.log1p(image)

        # Normalize to 14-bit range (typical for DR)
        image = (image - image.min()) / (image.max() - image.min()) * 16383

        return image.astype(np.uint16)

    def _add_simulated_anatomy(
        self,
        image: np.ndarray,
        params: ExposureParameters,
    ) -> np.ndarray:
        """Add simulated anatomical structures."""
        h, w = image.shape

        # Add some circular structures (simulate ribs/organs)
        y, x = np.ogrid[:h, :w]
        for _ in range(10):
            cx, cy = np.random.randint(w // 4, 3 * w // 4), np.random.randint(h // 4, 3 * h // 4)
            r = np.random.randint(50, 200)
            attenuation = np.random.uniform(0.3, 0.8)
            mask = (x - cx) ** 2 + (y - cy) ** 2 < r**2
            image[mask] *= attenuation

        return image

    def calibrate(self, **params) -> DeviceCalibration:
        """Calibrate the X-ray system."""
        self._status = DeviceStatus.MAINTENANCE

        try:
            calibration_params = {
                "tube_output": self._calibrate_tube_output(),
                "detector_uniformity": self._calibrate_detector_uniformity(),
                "aec_calibration": self._calibrate_aec(),
            }

            self._calibration = DeviceCalibration(
                calibration_date=datetime.now(),
                calibration_parameters=calibration_params,
                is_valid=True,
                expiry_date=datetime.now() + timedelta(days=365),
            )

            self._status = DeviceStatus.READY
            return self._calibration
        except Exception as e:
            self.log_error(f"Calibration failed: {str(e)}")
            raise

    def _calibrate_tube_output(self) -> dict:
        """Calibrate X-ray tube output."""
        return {
            "output_consistency": 0.98,
            "kvp_accuracy": 0.99,
            "ma_accuracy": 0.97,
        }

    def _calibrate_detector_uniformity(self) -> dict:
        """Calibrate detector uniformity."""
        return {
            "uniformity_coefficient": 0.95,
            "dead_pixels": 12,
            "gain_correction_applied": True,
        }

