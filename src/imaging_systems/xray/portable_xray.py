    def initialize(self) -> bool:
        """Initialize the portable X-ray system."""
        try:
            self._status = DeviceStatus.INITIALIZING

            # Check battery
            if self._battery_level < 10:
                raise RuntimeError("Battery too low for operation")

            # Initialize tube warm-up
            self._tube_warmup()

            # Self-test
            self._run_self_test()

            self._status = DeviceStatus.READY
            return True
        except Exception as e:
            self.log_error(f"Initialization failed: {str(e)}")
            return False

