class XRayTubeType(Enum):
    """X-ray tube types."""

    ROTATING_ANODE = "rotating_anode"
    STATIONARY_ANODE = "stationary_anode"
    CERAMIC = "ceramic"


@dataclass
class ExposureParameters:
    """X-ray exposure parameters."""

    kvp: float  # Kilovoltage peak
    ma: float  # Milliamperage
    exposure_time: float  # Seconds
    focal_spot: str  # "small" or "large"
    sfd: float  # Source-to-film distance (cm)

    @property
    def mas(self) -> float:
        """Calculate mAs (milliampere-seconds)."""
        return self.ma * self.exposure_time

    def validate(self) -> bool:
        """Validate exposure parameters are within safe ranges."""
        if not (40 <= self.kvp <= 150):
            return False
        if not (0.5 <= self.ma <= 500):
            return False
        if not (0.001 <= self.exposure_time <= 10):
            return False
        if not (50 <= self.sfd <= 200):
            return False
        return True


@dataclass
class XRayTube:
    """X-ray tube specifications."""

    tube_type: XRayTubeType
    max_kvp: float
    max_ma: float
    focal_spot_sizes: tuple[float, float]  # (small, large) in mm
    anode_angle: float  # degrees
    heat_capacity: float  # HU (Heat Units)
    current_heat: float = 0.0

    def calculate_heat_units(self, kvp: float, ma: float, time: float) -> float:
        """Calculate heat units generated by exposure."""
        return kvp * ma * time

    def can_expose(self, kvp: float, ma: float, time: float) -> bool:
        """Check if tube can handle the exposure."""
        hu = self.calculate_heat_units(kvp, ma, time)
        return (self.current_heat + hu) < self.heat_capacity

    def add_heat(self, kvp: float, ma: float, time: float):
        """Add heat from exposure."""
        self.current_heat += self.calculate_heat_units(kvp, ma, time)

    def cool_down(self, cooling_rate: float = 1000.0, time: float = 1.0):
        """Simulate tube cooling."""
        self.current_heat = max(0, self.current_heat - cooling_rate * time)


